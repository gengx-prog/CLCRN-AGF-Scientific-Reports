def bh(p):
    order=np.argsort(p); result=np.empty(len(p)); adjusted=np.minimum.accumulate((np.array(p)[order]*len(p)/np.arange(1,len(p)+1))[::-1])[::-1];result[order]=np.minimum(adjusted,1);return result
def exactperm(a,b):
    both=np.r_[a,b];obs=abs(a.mean()-b.mean());diff=[]
    for inds in itertools.combinations(range(10),5):
        x=both[list(inds)]; diff.append(abs(x.mean()-(both.sum()-x.sum())/5))
    return np.mean(np.array(diff)>=obs-1e-12)
def compare(a,b):
    # a is AGF, b is control. Welch is unpaired by design.
    va=a.var(ddof=1);vb=b.var(ddof=1);se=np.sqrt(va/len(a)+vb/len(b));df=(va/len(a)+vb/len(b))**2/((va/len(a))**2/(len(a)-1)+(vb/len(b))**2/(len(b)-1));delta=a.mean()-b.mean();width=stats.t.ppf(.975,df)*se
    return {'control_mean':b.mean(),'control_sd':b.std(ddof=1),'agf_mean':a.mean(),'agf_sd':a.std(ddof=1),'difference':delta,'ci95_low':delta-width,'ci95_high':delta+width,'welch_df':df,'welch_p':stats.ttest_ind(a,b,equal_var=False).pvalue,'exact_permutation_p':exactperm(a,b),'relative_change_percent':delta/b.mean()*100}

