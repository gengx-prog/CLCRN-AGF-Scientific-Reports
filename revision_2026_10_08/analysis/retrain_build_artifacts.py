def build(run_root, data_dir, figure_dir):
    global ROOT,DATA,FIG
    ROOT=Path(run_root).resolve();DATA=Path(data_dir).resolve();FIG=Path(figure_dir).resolve()
    rows=[load(p) for p in sorted(DATA.glob('inference_*.json'))]
    expected={(t,v,s) for t in TASKS for v in ['control','agf'] for s in range(2021,2026)} | {(t,'mean_fusion',s) for t in ['temperature','humidity'] for s in [2023,2024,2025]}
    assert len(rows)==46 and {(r['dataset'],r['kind'],r['seed']) for r in rows}==expected
    assert all(r['training_performed'] and r['training_protocol']=='zero_inclusive' and r['training_precision']=='FP32' and r['epochs_completed']==100 for r in rows)
    for r in rows:
        m=r['metrics']
        assert abs(m['cumulative_mae'][-1]-m['mae'])<1e-12
        assert abs(m['cumulative_rmse'][-1]-m['rmse'])<1e-12
        if r['kind'] in ['agf','control']:
            assert len(r['robustness'])==13
            assert all(x['n_examples']==64 for x in r['robustness'])
        if r['kind']=='agf':
            g=r['gates'];assert g['n_scalar_gates']==g['n_test_examples']*g['input_steps']*g['nodes']*g['gate_channels']
    main()
    assets=load(DATA/'manuscript_assets.json')
    assets['manuscript_updated']=False
    assets['evidence_source']='46 newly trained runs only; no historical inference mixed in'
    dump(DATA/'manuscript_assets.json',assets)
    lines=['New training analysis completed: 40 primary runs and 6 mean-fusion ablations.',
           'All runs completed 100 epochs with FP32 and zero-inclusive training and validation.',
           'The checkpoint is selected solely by minimum full validation MAE.',
           'Primary statistics: five independent runs per variant; Welch comparison, exact permutation sensitivity and BH adjustment.',
           'Ablations: temperature and humidity, three seeds each; main-run control/AGF checkpoints are reused.',
           'Robustness: diagnostic subset of 64 test windows, three mask seeds; not full-test performance.',
           'Manuscript has NOT been updated. Interpret these new results before revising claims.', '']
    for r in assets['statistics']:
        lines.append(f"{r['dataset']} {r['metric']}: control {r['control_mean']:.6g} +/- {r['control_sd']:.4g}; AGF {r['agf_mean']:.6g} +/- {r['agf_sd']:.4g}; relative change {r['relative_change_percent']:+.3f}%; Welch p={r['welch_p']:.6g}, BH q={r['welch_bh_q']:.6g}.")
    (DATA.parent/'RESULTS_README.txt').write_text('\n'.join(lines)+'\n',encoding='utf-8')


